"""Real UI regression, with isolated browser profiles and explicit storage-failure fixtures."""
import json, pathlib, sys
from playwright.sync_api import sync_playwright

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / '.qa' / 'browser'
OUT.mkdir(parents=True, exist_ok=True)
URL = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:4318/game-work/src/'
KEY = 'mosslight-post-v1'
report = {'url': URL, 'checks': [], 'errors': []}
def check(condition, name):
    assert condition, name
    report['checks'].append(name)
def snapshot(page):
    return json.loads(page.evaluate('window.render_game_to_text()'))
def ready(page):
    page.wait_for_function("typeof window.render_game_to_text === 'function' && document.querySelector('#scene-targets')")
    page.wait_for_timeout(150)
def action(page, name, item=None):
    query=f'[data-action="{name}"]' + (f'[data-id="{item}"]' if item else '')
    page.locator(query).click()
    page.wait_for_timeout(45)

with sync_playwright() as p:
    browser = p.chromium.launch()
    context = browser.new_context(viewport={'width':1440,'height':1000}, accept_downloads=True)
    page = context.new_page()
    page.on('pageerror', lambda e: report['errors'].append(str(e)))
    page.goto(URL); ready(page)
    check(snapshot(page)['progress']['lettersDone']==0, 'new profile starts with zero letters')
    page.screenshot(path=str(OUT/'home-1440.png'), full_page=True)
    action(page,'prepare','letter-1'); action(page,'start')
    action(page,'step','r0'); action(page,'step','r2')
    before=snapshot(page)
    check(before['trip']['collection']==3 and before['trip']['energy']==4, 'first visit includes basket harvest and tea')
    action(page,'rewind'); check(snapshot(page)['trip']['position']=='fork', 'undo restores previous crossing')
    action(page,'step','r2'); page.reload(); ready(page)
    check(snapshot(page)['trip']==before['trip'], 'mid-route refresh restores path energy and rewards')
    action(page,'step','r4'); action(page,'step','r11')
    first=snapshot(page)
    check(first['progress']['lettersDone']==1 and first['materials']==5, 'arrival settles harvest plus first delivery exactly once')
    check(first['plots'][0]=='bench' and first['progress']['friendsMet']==1, 'first gift appears in an empty garden plot')
    page.screenshot(path=str(OUT/'first-return-1440.png'), full_page=True)
    action(page,'go-decor'); action(page,'decor','stump'); action(page,'buy','stump')
    action(page,'world-plot','porch-left')
    check(snapshot(page)['plots'][4]=='stump' and snapshot(page)['materials']==3,'buy and place a real decoration')
    action(page,'world-plot','porch-right')
    check(snapshot(page)['plots'][5]=='stump' and snapshot(page)['materials']==3,'owned decoration can be placed twice without extra cost')
    action(page,'remove-decor'); action(page,'world-plot','porch-left')
    check(snapshot(page)['plots'][4] is None, 'remove keeps owned inventory')
    page.locator('#settings-open').click()
    with page.expect_download() as download: action(page,'export')
    backup=OUT/'first-save.json'; download.value.save_as(str(backup))
    saved=json.loads(backup.read_text(encoding='utf-8'))
    check(saved['completedLetters']==['letter-1'],'export downloads actual progress')
    page.locator('#modal-close').click()
    second=context.new_page();second.goto(URL);ready(second)
    second.locator('[data-tab="decor"]').click();action(second,'decor','bench');action(second,'world-plot','porch-left')
    page.wait_for_function("JSON.parse(window.render_game_to_text()).plots[4] === 'bench'")
    check(snapshot(page)['revision']==snapshot(second)['revision'],'another tab synchronizes committed progress')
    second.close()
    page.locator('#settings-open').click()
    page.locator('#import-file').set_input_files(str(backup))
    page.locator('[data-action="confirm-import"]').wait_for()
    action(page,'confirm-import')
    check(snapshot(page)['plots'][4] is None,'confirmed backup import replaces current progress')
    page.locator('#music-toggle').click()
    page.wait_for_function("JSON.parse(window.render_game_to_text()).audio.playing === true")
    check(snapshot(page)['audio']['playing'],'original OGG music decodes and plays after user action')
    page.locator('#music-toggle').click()
    page.wait_for_function("JSON.parse(window.render_game_to_text()).audio.playing === false")
    check(not snapshot(page)['audio']['playing'],'music toggle pauses playback')
    page.locator('[data-tab="home"]').click()
    with page.expect_download() as download:page.locator('#postcard').click()
    picture=OUT/'postcard.png';download.value.save_as(str(picture))
    check(picture.stat().st_size>10000,'garden postcard exports rendered PNG')

    plan_path=ROOT/'tests'/'playthrough-plan.json'
    if plan_path.exists():
        story=context.new_page();story.goto(URL);ready(story)
        # New isolated profile: all progression below occurs through visible controls.
        fresh=browser.new_context(viewport={'width':1440,'height':1000})
        story.close();story=fresh.new_page();story.on('pageerror',lambda e:report['errors'].append(str(e)))
        story.goto(URL);ready(story)
        plans=json.loads(plan_path.read_text(encoding='utf-8'))
        if isinstance(plans,dict): plans=plans.get('plans',plans.get('letters'))
        for i,plan in enumerate(plans):
            if i:action(story,'go-home')
            action(story,'prepare',plan['letterId'])
            selected=snapshot(story)['pack']
            for tool in selected:
                if tool not in plan['pack']:action(story,'tool',tool)
            for tool in plan['pack']:
                if tool not in selected:action(story,'tool',tool)
            action(story,'start')
            for edge in plan['edgeIds']:action(story,'step',edge)
            check(snapshot(story)['progress']['lettersDone']==i+1,f'story letter {i+1} delivered through UI')
        final=snapshot(story)
        check(final['progress']['ending'] and final['progress']['friendsMet']==6,'nine-letter ending and all six friends reached without save injection')
        story.screenshot(path=str(OUT/'ending-1440.png'),full_page=True)
        story.locator('[data-tab="decor"]').click()
        for decor in ['firepit','backpack','barrel','bowls','stump','pinktree']:
            action(story,'decor',decor);action(story,'buy',decor)
        check(snapshot(story)['progress']['decorOwned']==12,'story route provides enough materials to own all twelve decorations')
        for decor,plot in zip(['whiteflowers','lantern','table','tent','pinktree','firepit','barrel','bench'],['fern-nook','bridge-side','stump-corner','stream-garden','porch-left','porch-right','garden-left','garden-right']):
            action(story,'decor',decor);action(story,'world-plot',plot)
        for theme in ['evergreen','blossom','riverside']:
            action(story,'theme',theme)
            check(snapshot(story)['theme']==theme,f'unlocked {theme} theme is selectable')
        story.screenshot(path=str(OUT/'garden-complete-1440.png'),full_page=True)
        story.reload();ready(story)
        check(snapshot(story)['progress']['ending'] and snapshot(story)['progress']['decorOwned']==12,'completed story and full garden survive reload')
        fresh.close()
    else: report['checks'].append('full-story plan pending; rerun once generated')

    for width in [390,320]:
        mobile=browser.new_context(viewport={'width':width,'height':844},is_mobile=True,has_touch=True,reduced_motion='reduce')
        phone=mobile.new_page();phone.on('pageerror',lambda e:report['errors'].append(str(e)));phone.goto(URL);ready(phone)
        check(phone.evaluate('document.documentElement.scrollWidth <= innerWidth'),f'{width}px home has no horizontal overflow')
        phone.screenshot(path=str(OUT/f'home-{width}.png'),full_page=True)
        action(phone,'prepare','letter-1');action(phone,'start');action(phone,'step','r0')
        check(phone.evaluate('document.documentElement.scrollWidth <= innerWidth'),f'{width}px route has no horizontal overflow')
        sizes=phone.locator('.world-target').evaluate_all('(els)=>els.map(e=>({w:e.getBoundingClientRect().width,h:e.getBoundingClientRect().height}))')
        check(all(s['w']>=44 and s['h']>=44 for s in sizes),f'{width}px map touch targets at least 44px')
        phone.screenshot(path=str(OUT/f'route-{width}.png'),full_page=True)
        mobile.close()

    faulty=browser.new_context();faulty.add_init_script("localStorage.setItem('mosslight-post-v1','{broken');")
    broken=faulty.new_page();broken.goto(URL);ready(broken)
    stale=faulty.new_page();stale.goto(URL);ready(stale)
    stale.evaluate("window.addEventListener('storage', event => event.stopImmediatePropagation(), {capture:true})")
    check(broken.locator('#modal').is_visible() and broken.evaluate("localStorage.getItem('mosslight-post-v1')")=='{broken','corrupt save is preserved and recovery dialog appears')
    with broken.expect_download() as download:action(broken,'export-raw')
    rawpath=OUT/'corrupt-original.json';download.value.save_as(str(rawpath))
    check(rawpath.read_text(encoding='utf-8')=='{broken','recovery exports original unmodified data')
    broken.locator('#import-file').set_input_files(str(backup))
    action(broken,'confirm-import')
    check(snapshot(broken)['storage']=='local' and json.loads(broken.evaluate("localStorage.getItem('mosslight-post-v1')"))['completedLetters']==['letter-1'],'backup recovery replaces corrupt data in persistent storage')
    if stale.locator('#modal').is_visible(): action(stale,'reset-corrupt')
    check(json.loads(stale.evaluate("localStorage.getItem('mosslight-post-v1')"))['completedLetters']==['letter-1'],'another tab recovery preserves the newer valid save')
    faulty.close()
    blocked=browser.new_context();blocked.add_init_script("Object.defineProperty(window,'localStorage',{get(){throw new DOMException('Storage unavailable','SecurityError')}})")
    memory=blocked.new_page();memory.goto(URL);ready(memory)
    check(memory.locator('#save-warning').is_visible(),'unavailable browser storage is visibly disclosed')
    action(memory,'prepare','letter-1');action(memory,'start');action(memory,'step','r0')
    check(snapshot(memory)['trip']['position']=='fork' and snapshot(memory)['storage']=='memory','memory-only mode remains playable')
    blocked.close()
    legacy=browser.new_context();legacy.add_init_script("Object.defineProperty(navigator,'locks',{value:undefined})")
    old=legacy.new_page();old.goto(URL);ready(old);action(old,'prepare','letter-1');action(old,'start')
    check(snapshot(old)['storage']=='memory' and old.evaluate("localStorage.getItem('mosslight-post-v1')") is None,'browser without Web Locks never performs unsafe shared writes')
    legacy.close()
    quota=browser.new_context()
    quota.add_init_script("if(!localStorage.getItem('mosslight-post-v1'))localStorage.setItem('mosslight-post-v1',"+json.dumps(backup.read_text(encoding='utf-8'))+");window.failWrites=false;const nativeSet=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(window.failWrites)throw new DOMException('Quota exceeded','QuotaExceededError');return nativeSet.call(this,k,v)}")
    local=quota.new_page();local.goto(URL);ready(local);remote=quota.new_page();remote.goto(URL);ready(remote)
    local.evaluate('window.failWrites=true');action(local,'prepare','letter-2');action(local,'tool','basket')
    local_progress=snapshot(local)
    remote.locator('#settings-open').click();action(remote,'setting','sound');action(remote,'setting','motion')
    local.wait_for_timeout(100)
    check(snapshot(local)['pack']==local_progress['pack'] and snapshot(local)['storage']=='memory','remote storage events preserve unsaved memory-only progress')
    quota.close()
    check(not report['errors'],'no uncaught browser errors')
    context.close();browser.close()
report['passed']=len(report['checks'])
(OUT/'report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps({'passed':report['passed'],'errors':report['errors'],'output':str(OUT)},ensure_ascii=False))
