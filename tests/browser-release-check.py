"""Bounded release integration: field guide, genuine old v1 source, audio module.

The saved entry is an explicit fixture generated by the canonical old engine,
not a downgraded new checkpoint. Audio is a separate real-media module fixture,
not evidence that a player visited all seven soundscapes during a normal run.
"""
import argparse
import hashlib
import json
import pathlib
import re
import subprocess
import sys
import time
from playwright.sync_api import sync_playwright

ROOT = pathlib.Path(__file__).resolve().parents[1]
OLD = pathlib.Path('E:/Proj/Active/MyWeb/cinder-below')
OUT = ROOT / '.qa' / 'release-check'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('url', nargs='?', default='http://127.0.0.1:4328/src/?test=1')
parser.add_argument('--regenerate-legacy', action='store_true', help='Generate the legacy fixture only when OLD still points to the original v1 source.')
OPTIONS = parser.parse_args()
URL = OPTIONS.url
SAVE = 'cinder-below-v1'
REPORT = {'url': URL, 'checks': [], 'page_errors': [], 'console_errors': [], 'screenshots': [],
          'scope': 'Real UI legacy import and bilingual journal; separate real-media audio module fixture. No complete run claim.'}

def check(ok, name, detail=None):
    REPORT['checks'].append({'name': name, 'passed': bool(ok), 'detail': detail})
    print(('PASS ' if ok else 'FAIL ') + name, flush=True)
    if not ok:
        raise AssertionError(name)

def state(page):
    return json.loads(page.evaluate('window.render_game_to_text()'))

def flush(page):
    page.evaluate('window.advanceTime(0)')
    return state(page)

def raw_save(page):
    return page.evaluate('(key) => localStorage.getItem(key)', SAVE)

def create_fixture():
    target = ROOT / 'tests' / 'fixtures' / 'canonical-v1-room2.json'
    metadata_path = target.with_name('canonical-v1-room2.metadata.json')
    if not OPTIONS.regenerate_legacy:
        data = json.loads(target.read_text(encoding='utf-8'))
        provenance = json.loads(metadata_path.read_text(encoding='utf-8'))
        check(data['checkpoint']['version'] == 1 and data['checkpoint']['room'] == 2 and 'totalRooms' not in data['checkpoint'] and len(provenance['source_sha256']) == 64, 'preserved canonical v1 fixture retains its original source provenance')
        REPORT['legacy_fixture'] = {**provenance, 'path': str(target), 'metadata': str(metadata_path), 'regenerated': False}
        return target, data
    target.parent.mkdir(parents=True, exist_ok=True)
    js = """import { createRun, enterRoom, snapshot } from './src/engine.js';
import { createDefaultSave, exportSave } from './src/storage.js';
const s=createRun({seed:424242,weapon:'needle'});
s.phase='exit';s.relics={cold:1};s.player.hp=4;s.player.novaCharge=33;
s.time=2.25;s.stats={kills:3,rooms:1,embers:11,shots:7,hits:5,damageTaken:2,elapsed:2.25};
enterRoom(s,'refuge');
const save=createDefaultSave();save.stats={runs:3,wins:1,kills:40,rooms:12,embers:300,bestRoom:6};
save.banked={kills:3,rooms:1,embers:11};save.settings={music:false,sfx:false,reduceMotion:false};
save.checkpoint=snapshot(s);console.log(exportSave(save));"""
    data = json.loads(subprocess.check_output(['node', '--input-type=module', '-e', js], cwd=OLD, text=True, encoding='utf-8'))
    check(data['checkpoint']['version'] == 1 and data['checkpoint']['room'] == 2 and 'totalRooms' not in data['checkpoint'], 'fixture is genuinely generated by canonical old v1 engine')
    target.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')
    REPORT['legacy_fixture'] = {'path': str(target), 'source': str(OLD / 'src' / 'engine.js'),
                                'source_sha256': hashlib.sha256((OLD / 'src' / 'engine.js').read_bytes()).hexdigest(),
                                'generation': 'Old createRun + explicit entry fixture + old enterRoom/snapshot/exportSave, without changing checkpoint version.'}
    metadata_path.write_text(json.dumps(REPORT['legacy_fixture'], ensure_ascii=False, indent=2), encoding='utf-8')
    REPORT['legacy_fixture']['regenerated'] = True
    return target, data

def new_page(browser, name):
    context = browser.new_context(viewport={'width': 1280, 'height': 900}, locale='en-US')
    page = context.new_page()
    page.on('pageerror', lambda e: REPORT['page_errors'].append({'scenario': name, 'error': str(e)}))
    page.on('console', lambda m: REPORT['console_errors'].append({'scenario': name, 'error': m.text}) if m.type == 'error' else None)
    page.goto(URL, wait_until='domcontentloaded')
    page.wait_for_function("typeof window.render_game_to_text==='function' && JSON.parse(window.render_game_to_text()).ui.ready")
    return context, page

def capture(page, name):
    path = OUT / name
    page.screenshot(path=str(path), full_page=True)
    REPORT['screenshots'].append(str(path))

def legacy_and_journal(browser, fixture_path, saved):
    context, page = new_page(browser, 'legacy-and-journal')
    page.locator('#pause-button').click()
    page.locator('#import-file').set_input_files(str(fixture_path))
    page.locator('#confirm-import').wait_for(state='visible')
    page.locator('#confirm-import').click()
    page.locator('#resume-run').wait_for(state='visible')
    check(json.loads(raw_save(page))['checkpoint'] == saved['checkpoint'], 'normal confirmed import preserves the genuine v1 checkpoint exactly')
    page.locator('#resume-run').click()
    resumed = flush(page)
    cp = saved['checkpoint']
    check(resumed['campaign'] == 'legacy' and resumed['totalRooms'] == 8 and resumed['room'] == 2, 'old room2 resumes the eight-room campaign')
    check(resumed['seed'] == cp['seed'] and resumed['route'] == cp['route'] and resumed['relics'] == cp['relics'] and resumed['stats'] == cp['stats'], 'old seed route relics and complete run statistics remain unchanged')
    check(resumed['player']['weapon'] == cp['weapon'] and resumed['player']['hp'] == cp['hp'] and resumed['player']['novaCharge'] == cp['novaCharge'], 'old weapon hearts and nova charge remain unchanged')
    check(resumed['ui']['lifetime'] == saved['stats'], 'resuming does not re-bank old lifetime progress')
    page.locator('#pause-button').click()
    paused = flush(page)
    before = raw_save(page)
    page.locator('#menu-journal').click()
    names_zh = page.locator('#menu-body p > strong').all_text_contents()
    check(len(names_zh) == 30 and all(re.search('[\u4e00-\u9fff]', n) for n in names_zh), 'paused Chinese field guide displays all twenty enemies and ten bosses', names_zh)
    check(raw_save(page) == before, 'opening the field guide leaves the game save byte-for-byte unchanged')
    capture(page, 'journal-zh.png')
    page.locator('#menu-language-toggle').click()
    names_en = page.locator('#menu-body p > strong').all_text_contents()
    check(len(names_en) == 30 and all(not re.search('[\u4e00-\u9fff]', n) for n in names_en), 'open English field guide immediately displays all thirty translated entries', names_en)
    after = flush(page)
    check(after['ui']['paused'] and after['ui']['menuOpen'] and after['stats'] == paused['stats'] and after['ui']['lifetime'] == paused['ui']['lifetime'] and after['player'] == paused['player'], 'journal language switch keeps the same run paused without re-banking')
    check(raw_save(page) == before, 'journal language switch leaves the complete game save byte-for-byte unchanged')
    page.locator('#menu-language-toggle').click()
    check(page.locator('#menu-body p > strong').all_text_contents() == names_zh and raw_save(page) == before, 'journal language roundtrip restores Chinese without save writes')
    REPORT['legacy_resumed'] = {k: resumed[k] for k in ['seed', 'room', 'totalRooms', 'campaign', 'relics', 'stats']}
    context.close()

def audio_module(browser):
    context, page = new_page(browser, 'real-media-audio-module')
    page.locator('#pause-button').click()
    page.evaluate("""async () => {
      const {createAudio}=await import('./audio.js');
      const NativeAudio=window.Audio;window.__releaseMedia=[];window.__releaseAudioWarnings=[];
      window.Audio=class extends NativeAudio {constructor(...args){super(...args);window.__releaseMedia.push(this)}};
      window.__releaseAudio=createAudio(()=>window.__releaseAudioWarnings.push('unavailable'));
      const button=document.createElement('button');button.id='release-audio-unlock';button.textContent='Audio fixture: enable';
      document.querySelector('#menu-body').replaceChildren(button);
      button.onclick=async()=>{await window.__releaseAudio.configure({music:true,sfx:false});button.dataset.ready='true'};
    }""")
    page.locator('#release-audio-unlock').click()
    page.wait_for_function("document.querySelector('#release-audio-unlock').dataset.ready==='true'")
    tracks = [('dungeon', {'title': True}, 'music-dungeon.ogg'), ('fight', {'boss': True}, 'music-fight.ogg'),
              ('mire', {'biome': 'mire'}, 'music-aquatic.ogg'), ('cinder', {'biome': 'cinder'}, 'music-dark-castle.ogg'),
              ('storm', {'biome': 'storm'}, 'music-tension.ogg'), ('void', {'biome': 'void'}, 'music-final-area.ogg'),
              ('rift', {'biome': 'rift'}, 'music-dream.ogg')]
    REPORT['audio_module'] = {'evidence': 'Separate createAudio instance with real AudioContext, downloaded media playback, no mocks; not normal gameplay coverage.', 'tracks': []}
    for track, scene, filename in tracks:
        page.evaluate('(scene)=>window.__releaseAudio.setScene(scene)', scene)
        page.wait_for_function("([track,file])=>{const s=window.__releaseAudio.status(),m=window.__releaseMedia[0];return s.track===track&&s.musicPlaying&&m.currentSrc.endsWith(file)&&m.readyState>=2&&Number.isFinite(m.duration)&&m.duration>0}", arg=[track, filename], timeout=12000)
        start = page.evaluate('window.__releaseMedia[0].currentTime')
        page.wait_for_timeout(180)
        media = page.evaluate('({status:window.__releaseAudio.status(),src:window.__releaseMedia[0].currentSrc,duration:window.__releaseMedia[0].duration,time:window.__releaseMedia[0].currentTime,readyState:window.__releaseMedia[0].readyState})')
        check(media['time'] > start, f'audio setScene {track} maps to and actually plays {filename}', media)
        REPORT['audio_module']['tracks'].append(media)
    page.evaluate("window.__releaseAudio.setScene({biome:'mire'});window.__releaseAudio.suspend()")
    page.wait_for_timeout(700)
    stopped = page.evaluate('({status:window.__releaseAudio.status(),paused:window.__releaseMedia[0].paused,time:window.__releaseMedia[0].currentTime})')
    page.wait_for_timeout(250)
    after = page.evaluate('({status:window.__releaseAudio.status(),paused:window.__releaseMedia[0].paused,time:window.__releaseMedia[0].currentTime})')
    check(stopped['paused'] and after['paused'] and not after['status']['musicPlaying'] and after['status']['context'] == 'suspended' and abs(after['time'] - stopped['time']) < .02, 'suspend during delayed track fade stays stopped after all pending fades resolve', after)
    check(page.evaluate('window.__releaseAudioWarnings.length') == 0, 'real audio fixture reports no unavailable recordings')
    REPORT['audio_module']['suspended'] = after
    context.close()

def boss_hud(browser):
    js = """import {createRun,enterRoom,snapshot} from './src/engine.js';
import {createDefaultSave,exportSave} from './src/storage.js';
const s=createRun({seed:424242});s.room=2;s.phase='exit';s.stats.rooms=2;s.relics={cold:2};enterRoom(s,'refuge');
const save=createDefaultSave();save.stats={runs:1,wins:0,kills:0,rooms:2,embers:0,bestRoom:3};
save.banked={kills:0,rooms:2,embers:0};save.settings={music:false,sfx:false,reduceMotion:false};save.checkpoint=snapshot(s);console.log(exportSave(save));"""
    saved = json.loads(subprocess.check_output(['node', '--input-type=module', '-e', js], cwd=ROOT, text=True, encoding='utf-8'))
    target = ROOT / 'tests' / 'fixtures' / 'modern-v2-boss-room3.json'
    target.write_text(json.dumps(saved, ensure_ascii=False, indent=2), encoding='utf-8')
    context, page = new_page(browser, 'boss-room3-hud')
    page.locator('#pause-button').click()
    page.locator('#import-file').set_input_files(str(target))
    page.locator('#confirm-import').click()
    page.locator('#resume-run').click()
    s = flush(page)
    boss = next(e for e in s['enemies'] if e['boss'])
    check(s['room'] == 3 and boss['type'] == s['bossId'], 'room3 actual generated boss exposes a truthful read-only boss marker')
    expected = page.evaluate("async id=>(await import('./field-guide.js')).fieldGuide().find(e=>e.id===id).name", boss['type'])
    check(page.locator('#boss-hud').is_visible() and page.locator('#boss-name').inner_text() == expected, 'room3 independent boss HUD shows the localized actual boss name', {'type': boss['type'], 'name': expected})
    box = page.locator('#boss-fill').bounding_box()
    check(page.locator('#boss-fill').is_visible() and box['width'] > 100 and box['height'] > 0 and page.locator('#boss-fill').evaluate('e=>e.style.width') == '100%', 'room3 boss health bar is visible and initially full', box)
    capture(page, 'boss-room3-hud.png')
    page.locator('#language-toggle').click()
    expected_en = page.evaluate("async id=>(await import('./field-guide.js')).fieldGuide().find(e=>e.id===id).name", boss['type'])
    check(page.locator('#boss-name').inner_text() == expected_en and page.locator('#boss-hud').is_visible(), 'boss HUD name switches to English without losing the health bar', expected_en)
    REPORT['boss_fixture'] = {'path': str(target), 'type': boss['type'], 'seed': s['seed'], 'room': s['room'], 'evidence': 'Explicit entry fixture, real import/resume and DOM visibility; not defeated-boss evidence.'}
    context.close()

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    started = time.perf_counter()
    try:
        fixture_path, saved = create_fixture()
        with sync_playwright() as p:
            browser = p.chromium.launch(headless=True)
            REPORT['browser'] = browser.version
            try:
                legacy_and_journal(browser, fixture_path, saved)
                boss_hud(browser)
                audio_module(browser)
            finally:
                browser.close()
    except Exception as error:
        REPORT['failure'] = str(error)
        print('STOP ' + str(error), flush=True)
    REPORT['wall_seconds'] = round(time.perf_counter() - started, 2)
    REPORT['passed'] = not REPORT.get('failure') and not REPORT['page_errors'] and not REPORT['console_errors'] and all(c['passed'] for c in REPORT['checks'])
    (OUT / 'report.json').write_text(json.dumps(REPORT, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps({'passed': REPORT['passed'], 'checks': len(REPORT['checks']), 'failure': REPORT.get('failure'), 'wall_seconds': REPORT['wall_seconds'], 'page_errors': REPORT['page_errors'], 'console_errors': REPORT['console_errors']}), flush=True)
    return 0 if REPORT['passed'] else 1

if __name__ == '__main__':
    raise SystemExit(main())
