"""Exercise the shipped UI and deterministic simulation through real browser input."""
import argparse, json, math
from browser_navigation import die_from_real_damage
from pathlib import Path
from playwright.sync_api import sync_playwright

parser = argparse.ArgumentParser()
parser.add_argument('--url', default='http://127.0.0.1:4328/src/?test=1')
parser.add_argument('--out', default='.qa/ui-check')
args = parser.parse_args()
out = Path(args.out); out.mkdir(parents=True, exist_ok=True)
checks = []; errors = []
def check(name, value, detail=None):
    checks.append({'name': name, 'passed': bool(value), 'detail': detail})
    if not value: raise AssertionError(f'{name}: {detail}')
def state(p): return json.loads(p.evaluate('window.render_game_to_text()'))
def advance(p, ms): p.evaluate('(ms)=>window.advanceTime(ms)', ms)
def ready(p): p.goto(args.url); p.wait_for_function('window.render_game_to_text && JSON.parse(window.render_game_to_text()).ui.ready')
def screenshot(p, name): p.screenshot(path=str(out / (name + '.png')), full_page=True)

with sync_playwright() as pw:
    browser = pw.chromium.launch(headless=True)
    context = browser.new_context(viewport={'width': 1440, 'height': 900}, reduced_motion='reduce')
    page = context.new_page(); page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('response', lambda r: errors.append(f'HTTP {r.status}: {r.url}') if r.status >= 400 else None)
    ready(page); screenshot(page, 'desktop-title')
    art = state(page)['ui']['art']
    check('all declared art ready', art['loaded'] == art['total'] and art['total'] >= 55 and not art['failed'])
    check('initial weapon only', state(page)['ui']['unlockedWeapons'] == ['cinder'])
    page.locator('#play').click(); advance(page, 150)
    start = state(page)
    page.keyboard.down('a'); advance(page, 220); page.keyboard.up('a')
    moved = state(page); check('WASD moves left', moved['player']['x'] < start['player']['x'] - 20)
    page.keyboard.down('ArrowUp'); advance(page, 700); page.keyboard.up('ArrowUp')
    check('keyboard aims and shoots', state(page)['stats']['shots'] > 0)
    page.keyboard.press('Space'); advance(page, 40)
    check('dash input starts dash', state(page)['player']['dashCooldown'] > 0)
    page.keyboard.press('e'); advance(page, 40)
    check('nova consumes charge', state(page)['player']['novaCharge'] < 100)
    page.keyboard.press('Escape'); paused = state(page); advance(page, 1500)
    check('pause freezes simulation', paused['ui']['paused'] and state(page)['time'] == paused['time'])
    check('pause clears held input', not state(page)['ui']['input']['keys'])
    screenshot(page, 'pause-settings')
    page.locator('#continue').click(); advance(page, 200)
    check('resume advances simulation', state(page)['time'] > paused['time'])
    page.locator('#fullscreen').click()
    page.wait_for_function('!!document.fullscreenElement')
    check('fullscreen button invokes browser fullscreen', page.evaluate('!!document.fullscreenElement'))
    page.locator('#fullscreen').click()
    page.wait_for_function('!document.fullscreenElement')
    check('fullscreen exits', not page.evaluate('!!document.fullscreenElement'))
    if state(page)['ui']['paused']: page.locator('#continue').click()
    page.locator('#audio-toggle').click()
    check('mute toggle silences music', not state(page)['ui']['audio']['musicPlaying'])
    page.locator('#audio-toggle').click()
    page.wait_for_function('JSON.parse(window.render_game_to_text()).ui.audio.effectsReady')
    check('downloaded effects decoded', state(page)['ui']['audio']['effectsReady'])
    check('music plays after gesture', state(page)['ui']['audio']['musicPlaying'])
    page.locator('#pause-button').click(); page.locator('#abandon').click()
    check('return to title keeps checkpoint', page.locator('#resume-run').is_visible())
    page.locator('#resume-run').click(); advance(page, 120)
    check('resume starts same seeded room', state(page)['seed'] == start['seed'] and state(page)['room'] == 1)
    page.keyboard.down('d'); advance(page, 100); page.evaluate('window.dispatchEvent(new Event("blur"))')
    check('blur pauses and clears keys', state(page)['ui']['paused'] and not state(page)['ui']['input']['keys'])
    page.keyboard.up('d'); page.locator('#continue').click(); screenshot(page, 'desktop-combat')
    damage_evidence = die_from_real_damage(page)
    check('actual enemy damage reaches loss screen', state(page)['phase'] == 'dead' and page.locator('#end-screen').is_visible()
        and state(page)['stats']['damageTaken'] > damage_evidence['initial_damage'], damage_evidence)
    screenshot(page, 'death')
    runs_before = state(page)['ui']['lifetime']['runs']; page.locator('#retry').click(); advance(page, 100)
    check('one click retry starts a fresh healthy run', state(page)['phase'] == 'combat' and state(page)['player']['hp'] == 6 and state(page)['ui']['lifetime']['runs'] == runs_before + 1)
    context.close()

    mobile = browser.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True, device_scale_factor=1, reduced_motion='reduce')
    p = mobile.new_page(); p.on('pageerror', lambda e: errors.append(str(e))); ready(p); screenshot(p, 'mobile-title')
    p.locator('#play').tap(); advance(p, 300)
    check('mobile arena fits viewport', p.evaluate('document.documentElement.scrollWidth <= innerWidth && document.documentElement.scrollHeight <= innerHeight'))
    move = p.locator('#move-stick').bounding_box(); aim = p.locator('#aim-stick').bounding_box()
    initial = state(p); client = mobile.new_cdp_session(p)
    a = {'x': move['x'] + move['width'] / 2, 'y': move['y'] + move['height'] / 2, 'id': 1}
    b = {'x': aim['x'] + aim['width'] / 2, 'y': aim['y'] + aim['height'] / 2, 'id': 2}
    client.send('Input.dispatchTouchEvent', {'type': 'touchStart', 'touchPoints': [a, b]})
    a['y'] -= 34; b['y'] -= 35
    client.send('Input.dispatchTouchEvent', {'type': 'touchMove', 'touchPoints': [a, b]}); advance(p, 450)
    after = state(p)
    check('two fingers move and shoot simultaneously', after['player']['y'] < initial['player']['y'] - 25 and after['stats']['shots'] > initial['stats']['shots'])
    client.send('Input.dispatchTouchEvent', {'type': 'touchEnd', 'touchPoints': []}); advance(p, 40)
    check('touch release clears both sticks', state(p)['ui']['input']['move'] == {'x': 0, 'y': 0} and state(p)['ui']['input']['aimStick'] == {'x': 0, 'y': 0})
    p.locator('#dash').tap(); advance(p, 30); check('touch dash works', state(p)['player']['dashCooldown'] > 0)
    p.locator('#nova').tap(); advance(p, 30); check('touch nova works', state(p)['player']['novaCharge'] < 100)
    advance(p, 400); screenshot(p, 'mobile-combat')
    p.set_viewport_size({'width': 844, 'height': 390}); advance(p, 100); rotated = state(p)
    check('rotation retains run and valid bounds', rotated['seed'] == initial['seed'] and 0 < rotated['player']['x'] < rotated['width'] and 0 < rotated['player']['y'] < rotated['height'])
    screenshot(p, 'mobile-landscape')
    p.locator('#pause-button').tap(); p.locator('#abandon').tap()
    resume_box = p.locator('#resume-run').bounding_box()
    check('short landscape Continue button remains unobstructed', p.evaluate('b=>document.elementFromPoint(b.x+b.width/2,b.y+b.height/2)?.closest("#resume-run")!==null', resume_box))
    screenshot(p, 'landscape-title-with-resume'); p.locator('#resume-run').tap(); advance(p, 100)
    p.set_viewport_size({'width': 320, 'height': 568}); advance(p, 100)
    check('small mobile has no page overflow', p.evaluate('document.documentElement.scrollWidth <= innerWidth && document.documentElement.scrollHeight <= innerHeight'))
    screenshot(p, 'small-mobile')
    check('no browser errors', not errors, errors)
    mobile.close(); browser.close()
(out / 'report.json').write_text(json.dumps({'checks': checks, 'errors': errors}, indent=2), encoding='utf-8')
print(json.dumps({'passed': len(checks), 'errors': errors, 'report': str(out / 'report.json')}))
